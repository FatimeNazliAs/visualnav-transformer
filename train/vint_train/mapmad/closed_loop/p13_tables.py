"""Phase 13 fairness check, tables and the draft G13 table (p13_rules.md §7-§9), from the per-run scores
(p12_score.py `score` -> <subdir>/scores/<arm>.jsonl). numpy only, both containers.

    python -m vint_train.mapmad.closed_loop.p13_tables fairness --config <p13_claim.yaml>   # checks/fairness.json
    python -m vint_train.mapmad.closed_loop.p13_tables tables --config <p13_claim.yaml> [--out tables]

Sets: `hm3d` = the Phase 12 main exam (new arms M21b, M21bh, VF from runs/hm3d; the Phase 12 arms from
../p12_search_exam/runs/exam, reused, p13_rules §6), `examb` (MP3D val + test, runs/examb; rows split by home kind
too), `dev` (MP3D train homes, report only). Statistics = Phase 12's (p12_tables: per-episode mean over seeds, a
deterministic arm's one run counts for all; home-clustered bootstrap 10,000, seed 12601; paired over the episodes both
arms ran, crash records drop the episode). G13 rows 1-3 (one-sided home-clustered p, raw and Holm-adjusted over the
three rows); row 1's reading is the pre-set one (kickoff §3 item 4). Rule stop at tau 0.45 everywhere. Every table is
regenerated byte-identically from the same scores (§0.8 re-check).
"""

import argparse
import json
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

import numpy as np

from mapmad_sim.run_layout import RunLayout, parse_run_id, write_text_atomic
from mapmad_sim.run_plan_p13 import G13_ROWS, HM3D_OLD, P13Plan
from vint_train.mapmad.closed_loop.p12_tables import fmt, mean_ci, metric_fns, paired_diff, per_episode

TAU = "0.45"
OLD_HM3D = "../p12_search_exam/runs/exam"
CLAIM_MIN = 0.10  # kickoff §3 item 4: row 1 passing with a difference >= +0.10 -> "map effect holds with equal practice"
NAMES = {"M21": "MapMaD v2.1, maps shown", "M21h": "MapMaD v2.1, maps hidden", "M21b": "MapMaD v2.1b, maps shown",
         "M21bh": "MapMaD v2.1b, maps hidden", "M2": "MapMaD v2, maps shown", "M2h": "MapMaD v2, maps hidden",
         "N": "NoMaD explore", "F": "map + frontier planner", "VF": "VLFM-style (BLIP-2 value map)",
         "MT": "v2.1 + sim-truth layer", "V1": "MapMaD v1"}
Row = Dict[str, Any]


def holm(ps: Sequence[float]) -> List[float]:
    """Holm-adjusted p-values (step-down, monotone, capped at 1), in the input order."""
    order = np.argsort(ps)
    m, out, run = len(ps), [0.0] * len(ps), 0.0
    for rank, i in enumerate(order):
        run = max(run, min(1.0, (m - rank) * float(ps[i])))
        out[int(i)] = run
    return out


def reading(row1: Dict[str, Any], passed: bool) -> str:
    """Kickoff §3 item 4: the pre-set reading of M21b - M21bh on the HM3D exam."""
    if not passed:
        return ("row 1 fails -> the headline becomes 'map + practice'; the clean claim = M2 - M2h "
                "(+0.073 [+0.005, +0.147], Phase 12)")
    if row1["diff"] >= CLAIM_MIN:
        return f"passes and >= +{CLAIM_MIN:.2f} -> the map effect holds with equal practice"
    return f"passes but < +{CLAIM_MIN:.2f} -> the claim narrows to {row1['diff']:+.3f}"


class Sets:
    """Scores of every set and arm (module docstring)."""

    def __init__(self, layout: RunLayout) -> None:
        self.base, self.plan = layout.base, P13Plan.from_layout(layout)
        self.cache: Dict[Tuple[str, str], List[Row]] = {}

    def subdir(self, set_name: str, arm: str) -> str:
        if set_name == "hm3d":
            return OLD_HM3D if arm in HM3D_OLD else "runs/hm3d"
        return {"examb": "runs/examb", "dev": "runs/dev"}[set_name]

    def rows(self, set_name: str, arm: str) -> List[Row]:
        key = (set_name, arm)
        if key not in self.cache:
            f = self.base / self.subdir(set_name, arm) / "scores" / f"{arm}.jsonl"
            self.cache[key] = [json.loads(x) for x in f.read_text().splitlines()] if f.exists() else []
        return self.cache[key]

    def crashed(self, set_name: str, arm: str) -> set:
        d = self.base / self.subdir(set_name, arm) / "summaries" / arm
        return {parse_run_id(p.name)[0] for p in d.glob("*.crash.json")}

    def home(self, set_name: str) -> Dict[str, str]:
        f = self.plan.set_file(set_name)
        return {e["episode_id"]: e["home"] for e in json.loads(f.read_text())["episodes"]} if f.exists() else {}

    def kind(self, set_name: str) -> Dict[str, str]:
        """examb: home -> val | test (the set's freeze record)."""
        f = self.plan.set_file(set_name)
        return json.loads(f.read_text()).get("home_kind", {}) if f.exists() else {}

    def per_ep(self, set_name: str, arm: str, metric: str, keep: Optional[set] = None) -> Dict[str, float]:
        return per_episode(self.rows(set_name, arm), metric_fns(TAU)[metric], keep)

    def paired(self, set_name: str, a: str, b: str, metric: str = "oracle_success",
               keep: Optional[set] = None) -> Dict[str, Any]:
        drop = self.crashed(set_name, a) | self.crashed(set_name, b)
        ea = {k: v for k, v in self.per_ep(set_name, a, metric, keep).items() if k not in drop}
        eb = {k: v for k, v in self.per_ep(set_name, b, metric, keep).items() if k not in drop}
        return paired_diff(ea, eb, self.home(set_name))


# --- fairness (G13 row 5) -----------------------------------------------------------------------------------------
def cmd_fairness(args: argparse.Namespace) -> None:
    layout = RunLayout.load(args.config)
    plan = P13Plan.from_layout(layout)
    problems, n = [], 0
    for c in plan.calls("dev") + plan.calls("exams"):
        eps = plan.episode_ids(c.set)
        fp = json.loads(plan.set_file(c.set).read_text())["fingerprint"]
        for arm in c.arms:
            a = plan.table.arm(arm)
            want = None if a.policy in ("frontier", "vf") else plan.table.checkpoint(a.checkpoint).sha256
            for e in eps:
                for k in plan.arm_seeds(c, arm):
                    n += 1
                    rid = f"{e}__s{k}"
                    root = layout.base / c.subdir
                    if (root / "summaries" / arm / f"{rid}.crash.json").exists():
                        problems.append(f"crash {c.label} {arm} {rid}")
                        continue
                    log = root / "logs" / arm / f"{rid}.jsonl"
                    if not log.exists():
                        problems.append(f"missing {c.label} {arm} {rid}")
                        continue
                    head = json.loads(log.open().readline())
                    if head.get("episodes_fingerprint") != fp:
                        problems.append(f"fingerprint {arm} {rid}")
                    if want is not None and head.get("weights_sha256") != want:
                        problems.append(f"sha256 {arm} {rid}")
    res = {"pass": not problems, "runs": n, "problems": problems[:200], "n_problems": len(problems),
           "summary": f"{n} runs checked, {len(problems)} problems"}
    write_text_atomic(layout.base / "checks" / "fairness.json", json.dumps(res, indent=1) + "\n")
    print(res["summary"])


# --- tables -----------------------------------------------------------------------------------------------------
METRICS = ("oracle_success", "oracle_spl", "rule_success", "rule_spl", "seen", "collisions", "stuck")


def main_table(s: Sets, set_name: str, arms: Sequence[str], keep: Optional[set] = None) -> List[str]:
    home = s.home(set_name)
    out = ["| arm | oracle success | oracle SPL | rule success (tau 0.45) | rule SPL | seen share | collisions | stuck runs | episodes |",
           "|---|---|---|---|---|---|---|---|---|"]
    for a in arms:
        if not s.rows(set_name, a):
            continue
        v = {m: s.per_ep(set_name, a, m, keep) for m in METRICS}
        cells = [fmt(*mean_ci(v["oracle_success"], home)), fmt(np.mean(list(v["oracle_spl"].values()))),
                 fmt(*mean_ci(v["rule_success"], home)), fmt(np.mean(list(v["rule_spl"].values())) if v["rule_spl"] else None),
                 fmt(np.mean(list(v["seen"].values()))), f"{np.mean(list(v['collisions'].values())):.0f}",
                 fmt(np.mean(list(v["stuck"].values()))), str(len(v["oracle_success"]))]
        out.append(f"| {a} ({NAMES.get(a, a)}) | " + " | ".join(cells) + " |")
    return out


def group_table(s: Sets, set_name: str, arms: Sequence[str], key: str, labels: Dict[Any, str]) -> List[str]:
    groups = sorted({r[key] for a in arms for r in s.rows(set_name, a)})
    out = ["| arm | " + " | ".join(f"{labels.get(g, g)}" for g in groups) + " |", "|---|" + "---|" * len(groups)]
    for a in arms:
        rows = s.rows(set_name, a)
        if not rows:
            continue
        cells = []
        for g in groups:
            keep = {r["episode_id"] for r in rows if r[key] == g}
            o = s.per_ep(set_name, a, "oracle_success", keep)
            r_ = s.per_ep(set_name, a, "rule_success", keep)
            cells.append(f"{np.mean(list(o.values())):.3f} / {np.mean(list(r_.values())):.3f} ({len(o)})" if o else "-")
        out.append(f"| {a} | " + " | ".join(cells) + " |")
    return out


def search_table(s: Sets, set_name: str, arms: Sequence[str]) -> List[str]:
    out = ["| arm | found by 1,000 | first sight (median step) | oracle approach steps (median) | success if seen (oracle / rule) |",
           "|---|---|---|---|---|"]
    for a in arms:
        rows = s.rows(set_name, a)
        if not rows:
            continue
        seen = [r for r in rows if r["seen"]]
        fs = [r["first_sight"] for r in seen]
        ap = [r["oracle_approach_steps"] for r in rows if r["oracle_approach_steps"] is not None]
        so = np.mean([r["oracle_success"] for r in seen]) if seen else float("nan")
        sr = np.mean([r["rule"][TAU]["success"] for r in seen if r.get("rule")]) if seen else float("nan")
        out.append(f"| {a} | {len(seen) / len(rows):.3f} | {np.median(fs) if fs else '-'} | {np.median(ap) if ap else '-'} | "
                   f"{fmt(so)} / {fmt(sr)} |")
    return out


def paired_line(label: str, p: Dict[str, Any], with_p: bool = False) -> str:
    if not p.get("n"):
        return f"| {label} | - | - | - |"
    pv = f"{p['home_p_one_sided']:.4f}" if with_p else ""
    return (f"| {label} | {fmt(p['diff'], *p['home_ci'])} | {fmt(p['diff'], *p['episode_ci'])} | {p['n']} eps / "
            f"{p['homes']} homes {pv} |")


def cmd_tables(args: argparse.Namespace) -> None:
    layout = RunLayout.load(args.config)
    s, out_dir = Sets(layout), layout.base / args.out
    res: Dict[str, Any] = {"tau": TAU}
    md = ["# Phase 13 tables", "", "Oracle / rule stop (tau 0.45) from one 1,000-step log per run; home-clustered 95% CIs "
          "(10,000 resamples, seed 12601); per-episode mean over seeds.", ""]
    # G13 rows 1-3
    rows = [s.paired(st, a, b) for st, a, b in G13_ROWS]
    raw = [r.get("home_p_one_sided", 1.0) for r in rows]
    adj = holm(raw)
    g13 = []
    for (st, a, b), r, p_raw, p_adj in zip(G13_ROWS, rows, raw, adj):
        g13.append({"set": st, "a": a, "b": b, **{k: r.get(k) for k in ("n", "homes", "diff", "home_ci", "episode_ci")},
                    "p_raw": p_raw, "p_holm": p_adj, "pass": bool(r.get("n")) and r["diff"] > 0 and p_raw < 0.05})
    res["g13_rows_1_3"] = g13
    res["row1_reading"] = reading(g13[0], g13[0]["pass"]) if g13[0].get("n") else "row 1 not run"
    md += ["## G13 rows 1-3 (oracle success, a - b)", "", "| row | set | a - b | diff [home 95% CI] | p raw | p Holm | pass |",
           "|---|---|---|---|---|---|---|"]
    for k, r in enumerate(g13, 1):
        md.append(f"| {k} | {r['set']} | {r['a']} - {r['b']} | " + (fmt(r["diff"], *r["home_ci"]) if r.get("n") else "-")
                  + f" | {r['p_raw']:.4f} | {r['p_holm']:.4f} | {'PASS' if r['pass'] else 'FAIL'} |")
    md += ["", f"**Row 1 reading (pre-set, kickoff §3 item 4):** {res['row1_reading']}", ""]
    # rows 2-3 by exam-B home kind (report only; val = official MP3D episodes, test = generated view points + starts)
    kinds, home_b = s.kind("examb"), s.home("examb")
    md += ["## G13 rows 2-3 by exam-B home kind (report only, no Holm)", "",
           "| row | homes | a - b | diff [home 95% CI] | [episode CI] | p raw (one-sided) | n |", "|---|---|---|---|---|---|---|"]
    res["g13_rows_2_3_by_kind"] = {}
    for kd in ("val", "test"):
        keep = {e for e, h in home_b.items() if kinds.get(h) == kd}
        for k, (st, a, b) in enumerate(G13_ROWS[1:], 2):
            p = s.paired(st, a, b, keep=keep)
            res["g13_rows_2_3_by_kind"][f"{kd}:{a}-{b}"] = p
            md.append(f"| {k} | {kd} | {a} - {b} | {fmt(p['diff'], *p['home_ci'])} | {fmt(p['diff'], *p['episode_ci'])} | "
                      f"{p['home_p_one_sided']:.4f} | {p['n']} eps / {p['homes']} homes |" if p.get("n") else
                      f"| {k} | {kd} | {a} - {b} | - | - | - | 0 |")
    md.append("")
    # reported comparisons (row 4)
    rep = [("hm3d", "M21bh", "M21"), ("hm3d", "M21bh", "M21h"), ("hm3d", "M21b", "M21"), ("examb", "M21bh", "M21h"),
           ("examb", "M21b", "M21"), ("hm3d", "VF", "F"), ("hm3d", "VF", "M21"), ("hm3d", "VF", "N"),
           ("examb", "VF", "F"), ("examb", "VF", "M21"), ("examb", "VF", "N"), ("examb", "M21", "N"),
           ("examb", "M21", "F"), ("hm3d", "M2", "M2h")]
    md += ["## Reported paired differences (G13 row 4)", "", "| set: a - b | oracle success [home CI] | [episode CI] | n |",
           "|---|---|---|---|"]
    res["reported"] = {}
    for st, a, b in rep:
        p = s.paired(st, a, b)
        pr = s.paired(st, a, b, "rule_success")
        res["reported"][f"{st}:{a}-{b}"] = {"oracle": p, "rule": pr}
        md.append(paired_line(f"{st}: {a} - {b}", p))
        md.append(paired_line(f"{st}: {a} - {b} (rule stop)", pr))
    bins = {0: "3-6 m", 1: "6-10 m", 2: "10-15 m"}
    arm_sets = {"hm3d": ["M21b", "M21bh", "M21", "M21h", "M2", "M2h", "N", "F", "MT", "V1", "VF"],
                "examb": ["M21b", "M21bh", "M21", "M21h", "N", "F", "VF"], "dev": ["M21b", "M21bh", "F", "VF"]}
    md += ["## All arms, both exam sets (oracle / rule success at tau 0.45, home 95% CI on oracle)", "",
           "| arm | HM3D exam (300 eps) | exam B (MP3D) |", "|---|---|---|"]
    res["arms_both_sets"] = {}
    for a in arm_sets["hm3d"]:
        cells = []
        for st in ("hm3d", "examb"):
            if not s.rows(st, a):
                cells.append("not run")
                continue
            o, r = s.per_ep(st, a, "oracle_success"), s.per_ep(st, a, "rule_success")
            m, lo, hi = mean_ci(o, s.home(st))
            res["arms_both_sets"][f"{st}:{a}"] = {"oracle": m, "oracle_ci": [lo, hi], "rule": float(np.mean(list(r.values())))}
            cells.append(f"{fmt(m, lo, hi)} / {np.mean(list(r.values())):.3f}")
        md.append(f"| {a} ({NAMES.get(a, a)}) | " + " | ".join(cells) + " |")
    md.append("")
    for st, arms in arm_sets.items():
        md += [f"## {st}: main", ""] + main_table(s, st, arms) + [""]
        if st == "examb":
            kinds = s.kind("examb")
            home = s.home("examb")
            for kd in ("val", "test"):
                keep = {e for e, h in home.items() if kinds.get(h) == kd}
                md += [f"### examb, {kd} homes only", ""] + main_table(s, st, arms, keep) + [""]
        md += [f"## {st}: distance bins (oracle / rule success (episodes))", ""] + group_table(s, st, arms, "distance_bin", bins) + [""]
        md += [f"## {st}: categories", ""] + group_table(s, st, arms, "category", {}) + [""]
        md += [f"## {st}: search / approach", ""] + search_table(s, st, arms) + [""]
    res["port_check"] = port = port_check(layout.base / "vlfm_port" / "run_100")
    md += ["## VLFM port check (original code, 100 HM3D v2 val episodes; report only)", ""] + port_lines(port) + [""]
    out_dir.mkdir(parents=True, exist_ok=True)
    write_text_atomic(out_dir / "tables.md", "\n".join(md) + "\n")
    write_text_atomic(out_dir / "tables.json", json.dumps(res, indent=1, sort_keys=True, default=float) + "\n")
    g13_draft(layout.base, g13, res["row1_reading"])
    print("\n".join(md[:20]))


PORT_RADII = (0.1, 0.15, 0.2, 0.25, 0.3)  # 0.1 = VLFM's / Habitat's success distance; 0.2 = our exam's success_m
STOP_CAUSES = ("false_positive", "bad_stop_true_positive")  # VLFM's failure causes of a run that called STOP


def port_check(run: Path) -> Dict[str, Any]:
    """The port check's results.jsonl: success as run (Habitat, 0.1 m), the same stops re-scored at larger success
    radii (a STOP whose distance_to_goal <= r), failure causes, and a binomial 95% CI (Wilson) of the success rate."""
    f = run / "results.jsonl"
    if not f.exists():
        return {"n": 0}
    r = [json.loads(x) for x in f.read_text().splitlines()]
    n = len(r)

    def wilson(k: int) -> List[float]:
        p, z = k / n, 1.96
        c, h = (p + z * z / (2 * n)) / (1 + z * z / n), z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
        return [float(c - h), float(c + h)]

    radii = {}
    for rad in PORT_RADII:
        k = sum(1 for x in r if x["success"] or (x["failure_cause"] in STOP_CAUSES and x["distance_to_goal"] <= rad))
        radii[f"{rad:.2f}"] = {"success": k / n, "ci": wilson(k)}
    causes: Dict[str, int] = {}
    for x in r:
        causes[x["failure_cause"]] = causes.get(x["failure_cause"], 0) + 1
    return {"n": n, "spl": float(np.mean([x["spl"] for x in r])), "radii": radii, "causes": causes,
            "stopped_within_0_2_m_but_failed": sum(1 for x in r if not x["success"] and x["failure_cause"] in STOP_CAUSES
                                                   and x["distance_to_goal"] <= 0.2)}


def port_lines(port: Dict[str, Any]) -> List[str]:
    if not port.get("n"):
        return ["not run"]
    out = [f"{port['n']} episodes; SPL {port['spl']:.3f}; third-party HM3D v2 number for VLFM: 63.6% SR / 32.5 SPL "
           "(VLFM paper, HM3D v1: 52.5% / 30.4).", "", "| success radius (stops re-scored) | success [Wilson 95% CI] |",
           "|---|---|"]
    out += [f"| {k} m{' (as run)' if k == '0.10' else ''} | {fmt(v['success'], *v['ci'])} |" for k, v in port["radii"].items()]
    out += ["", "Failure causes (VLFM's own labels): " + ", ".join(f"{k} {v}" for k, v in sorted(port["causes"].items()))]
    return out


def read_check(base: Path, name: str) -> Dict[str, Any]:
    f = base / "checks" / name
    return json.loads(f.read_text()) if f.exists() else {"pass": None, "summary": "not run"}


def g13_draft(base: Path, g13: List[Dict[str, Any]], row1: str) -> None:
    fair, det, same, vid = (read_check(base, n) for n in ("fairness.json", "determinism.json", "video_same_run.json",
                                                          "video_check.json"))
    mark = {True: "PASS", False: "FAIL", None: "not run"}
    lines = ["# G13 draft (Phase 13; automatic part — Naz completes row 7 by watching the videos)", "",
             "| # | Check | Result | |", "|---|---|---|---|"]
    names = ("DAgger control (HM3D): M21b - M21bh", "Fresh replication (exam B): M21 - M21h",
             "Fresh control (exam B): M21b - M21bh")
    for k, (r, nm) in enumerate(zip(g13, names), 1):
        res = (fmt(r["diff"], *r["home_ci"]) + f", p raw {r['p_raw']:.4f}, Holm {r['p_holm']:.4f}") if r.get("n") else "not run"
        lines.append(f"| {k} | {nm} | {res} | {'PASS' if r['pass'] else 'FAIL'} |")
    lines += [f"| 4 | Reported | tables/tables.md | — |",
              f"| 5 | Fairness | {fair.get('summary')} | {mark[fair.get('pass')]} |",
              f"| 6 | Determinism | same GPU: {det.get('summary')}; Phase 12 reproduction: {same.get('summary')} | "
              f"{mark[det.get('pass')]} / {mark[same.get('pass')]} |",
              f"| 7 | Videos (automatic part) | {vid.get('summary')} | {mark[vid.get('pass')]} (+ Naz's review) |", "",
              f"Row 1 reading (pre-set): {row1}"]
    write_text_atomic(base / "G13_table_draft.md", "\n".join(lines) + "\n")


def main(argv: Optional[List[str]] = None) -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    q = sub.add_parser("fairness")
    q.add_argument("--config", required=True)
    q = sub.add_parser("tables")
    q.add_argument("--config", required=True)
    q.add_argument("--out", default="tables")
    args = p.parse_args(argv)
    {"fairness": cmd_fairness, "tables": cmd_tables}[args.cmd](args)


if __name__ == "__main__":
    main()
