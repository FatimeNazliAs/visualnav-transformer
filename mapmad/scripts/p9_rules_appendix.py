"""Freeze Phase 9's rules before scoring: <outputs>/p9_recognisers/p9_rules.md = mapmad/configs/p9_rules.md + Appendix A
(generated from the frozen frame set and the downloads) and p9_rules.md.sha256. Refuses to change an existing frozen
file (an identical re-run is fine). In naz_mapmad_habitat_p9:

    python mapmad/scripts/p9_rules_appendix.py
"""

import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from mapmad_sim import config  # noqa: E402
from mapmad_sim.run_info import git_state  # noqa: E402


def main() -> None:
    root = config.paths()["outputs"] / "p9_recognisers"
    fr = root / "frames"
    base = (config.CONFIG_DIR / "p9_rules.md").read_text()
    fp = json.loads((fr / "fingerprint.json").read_text())
    tables = json.loads((fr / "label_tables.json").read_text())
    ovon = json.loads((fr / "ovon_mapping.json").read_text())
    halves = json.loads((fr / "halves.json").read_text())
    items = {n: json.loads((fr / f"items_{n}.json").read_text()) for n in ("six", "ovon")}
    weights = json.loads((root / "photo_test" / "weights.json").read_text())
    lines = [f"Generated by p9_rules_appendix.py at commit {git_state()['commit']}.", "",
             "### A.1 Frame-set fingerprints", "```json", json.dumps(fp, indent=1), "```", "",
             f"Halves: A = {halves['A']}, B = {halves['B']} ({halves['rule']}, worst share {halves['worst_share']}).", "",
             "| category | items | positive | target-free | ignore-only | target-free share |", "|---|---|---|---|---|---|"]
    for key in sorted({i["key"] for i in items["six"]}):
        sel = [i for i in items["six"] if i["key"] == key]
        n = {s: sum(i["status"] == s for i in sel) for s in ("positive", "free", "ignore_only")}
        lines.append(f"| {key} | {len(sel)} | {n['positive']} | {n['free']} | {n['ignore_only']} | {n['free'] / len(sel):.3f} |")
    lines += ["", f"OVON: {len(items['ovon'])} items over {len({i['key'] for i in items['ovon']})} mapped names.", "",
              "### A.2 Label tables (6 categories)",
              f"Mapping file `{tables['category_map']}` sha256 `{tables['category_map_sha256']}`.", ""]
    for key, t in tables["six"].items():
        lines.append(f"- **{key}** (prompt `{t['prompt']}`): counted {t['counted']}; ignore {t['ignore']}")
    lines += ["", "### A.3 OVON mapping (by name)", ""]
    for split, names in ovon["splits"].items():
        mapped = [n for n in names if n in ovon["mapped"]]
        lines.append(f"- {split}: {len(names)} names, {len(mapped)} mapped: {mapped}")
    lines += [f"- unmapped: {sorted(ovon['unmapped'])}", "", "### A.4 Weights (sha256)", ""]
    for key, w in weights.items():
        if w.get("status") == "ok":
            lines.append(f"- {key}: {w['source']} @ {w['revision']}")
            lines += [f"  - `{f}` {h}" for f, h in w["files"].items()]
        else:
            lines.append(f"- {key}: NOT AVAILABLE at freeze time ({w.get('reason', '')}); SAM 3 is retried once before its turn")
    text = base.rstrip() + "\n\n" + "\n".join(lines) + "\n"
    out = root / "p9_rules.md"
    if out.exists() and out.read_text() != text:
        raise SystemExit(f"{out} is frozen and differs: not overwritten")
    out.write_text(text)
    digest = hashlib.sha256(text.encode()).hexdigest()
    (root / "p9_rules.md.sha256").write_text(f"{digest}  p9_rules.md\n")
    print(digest)


if __name__ == "__main__":
    main()
